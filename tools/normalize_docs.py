def build_header(num: str, title: str, body: str) -> str:
    """生成统一的文档控制块，保留原始标题中的编号与主题。"""
    module, deps, ver = DOC_META[num]
    m = re.search(r"^# (.+)$", body, re.M)
    raw_title = m.group(1).strip() if m else f"{num} · {module}"
    clean_title = re.sub(r"^#?\s*\d+\s*[·\-—]\s*", "", raw_title)
    clean_title = clean_title.replace("设计", "", 1) if clean_title.endswith("设计") else clean_title
    return (
        f"# {num} · {clean_title}\n\n"
        f"| 文档项 | 内容 |\n"
        f"|---|---|\n"
        f"| 模块 | {module} |\n"
        f"| 文档类型 | 设计报告（中文版） |\n"
        f"| 版本 | {ver} |\n"
        f"| 依赖 | {deps} |\n"
        f"| 语言 | 简体中文（英文版见 `../en-US/`） |\n\n"
        f"> **依据类别标注**：`[引用:…]` 文献或数据依据；`[设计决策]` 无外部依据的项目设定，"
        f"须注明可调性；`[逻辑推导]` 由已列前提与公式导出；`[待验证]` 数值或方法未经验证，"
        f"仅作占位，须注明供值方。所有关键断言均带上述类别之一。\n"
    )


def strip_frontmatter(lines: list[str]) -> list[str]:
    """移除原文头部（标题、元信息、依据标注规范）直到第一个水平分隔线。"""
    start = 0
    for i, ln in enumerate(lines[:40]):
        if ln.strip() == "---":
            start = i + 1
            break
    return lines[start:]


def strip_tail(lines: list[str]) -> list[str]:
    while lines and (not lines[-1].strip() or lines[-1].lstrip().startswith("*生成")):
        lines.pop()
    return lines


def apply_rules(line: str) -> str:
    for pat, rep in RULES:
        line = re.sub(pat, rep, line)
    return line


def clean_line(line: str, num: str) -> str | None:
    for pat in DROP_LINE:
        if re.search(pat, line):
            return None
    # 决策记录行：整行替换为规范陈述
    if re.search(r"^\s*>\s*\*\*(?:[ST]\d\s*)?(?:设计)?决策记录", line) or re.search(
        r"拍板记录|决策记录\*\*[:：]", line
    ):
        return f"> **{DECISIONS[num]}**\n"
    for pat in CLAUSE_DROP:
        line = re.sub(pat, "", line)
    line = apply_rules(line)
    return line.rstrip() + "\n" if line.strip() else "\n"


def polish_punctuation(text: str) -> str:
    """中文语境标点规范化；跳过代码块与表格分隔行。"""
    out, in_code = [], False
    for line in text.splitlines(keepends=True):
        if line.lstrip().startswith("```"):
            in_code = not in_code
            out.append(line)
            continue
        if in_code or re.match(r"^\s*\|[\s\-:|]+\|\s*$", line):
            out.append(line)
            continue
        line = re.sub(r"(?<=[\u4e00-\u9fff])\s*,\s*(?=[\u4e00-\u9fff])", "，", line)
        line = re.sub(r"(?<=[\u4e00-\u9fff])\s*;\s*(?=[\u4e00-\u9fff])", "；", line)
        line = re.sub(r"(?<=[\u4e00-\u9fff]):(?=[\u4e00-\u9fff])", "：", line)
        out.append(line)
    return "".join(out)


def normalize(path: Path) -> tuple[str, list[str]]:
    num = path.name[:2]
    raw = path.read_text(encoding="utf-8")
    header = build_header(num, "", raw)
    lines = strip_frontmatter(raw.splitlines(keepends=True))
    lines = strip_tail(lines)
    cleaned: list[str] = []
    for ln in lines:
        res = clean_line(ln.rstrip("\n"), num)
        if res is not None:
            cleaned.append(res)
    body = polish_punctuation("".join(cleaned))
    body = re.sub(r"\n{4,}", "\n\n\n", body)
    doc = header + "\n---\n\n" + body.lstrip("\n")
    if not doc.endswith("\n"):
        doc += "\n"
    # 残留检查
    hits = []
    for i, ln in enumerate(doc.splitlines(), 1):
        found = BAD_TERMS.findall(ln)
        if found:
            hits.append(f"L{i} <{'/'.join(sorted(set(found)))}>: {ln[:210]}")
    return doc, hits


def main() -> int:
    if not SRC.is_dir():
        print(f"未找到原文目录：{SRC}")
        return 1
    OUT.mkdir(parents=True, exist_ok=True)
    total = 0
    for src in sorted(SRC.glob("[0-9][0-9]_*.md")):
        doc, hits = normalize(src)
        (OUT / src.name).write_text(doc, encoding="utf-8")
        total += len(hits)
        print(f"[zh-CN] {src.name}: {len(doc)} chars, 残留 {len(hits)} 行")
        for h in hits:
            print("    " + h)
    print(f"\n合计残留命中：{total}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
